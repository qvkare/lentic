#!/usr/bin/env node
// Copies contract ABIs out of Foundry's build output into stable, committed locations:
//   contracts/abi/<Name>.json           — consumed by crates/lentic-base (alloy `sol!`)
//   web/src/generated/contracts.ts      — typed `as const` ABIs + known deployments for viem
// Run after `forge build` (and after a deploy, to pick up contracts/deployments/*.json).
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const CONTRACTS = ["LoanBook", "LenderVault", "AttestationVerifier", "MockUSDC"];

if (!existsSync(out)) {
  console.error("contracts/out not found — run `forge build` in contracts/ first");
  process.exit(1);
}

const abiDir = join(root, "contracts", "abi");
mkdirSync(abiDir, { recursive: true });
const abis = {};
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  abis[name] = artifact.abi;
  writeFileSync(join(abiDir, `${name}.json`), JSON.stringify(artifact.abi, null, 2) + "\n");
}

const deployments = {};
const depDir = join(root, "contracts", "deployments");
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    deployments[f.replace(".json", "")] = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  }
}

const ts = [
  "// Generated by scripts/export-abis.mjs — do not edit.",
  ...CONTRACTS.map((n) => `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abis[n])} as const;`),
  `export const deployments: Record<string, Record<string, string | number>> = ${JSON.stringify(deployments, null, 2)};`,
  "",
].join("\n\n");
const webGen = join(root, "web", "src", "generated");
mkdirSync(webGen, { recursive: true });
writeFileSync(join(webGen, "contracts.ts"), ts);

console.log(`exported ${CONTRACTS.length} ABIs; deployments: ${Object.keys(deployments).join(", ") || "none"}`);
